//! cargo-fuzz target — git bridge map and ref-state files (`bridge_map`).
//! See sibling `delta.rs` for guardrail rationale. Invariant: no panic on any
//! file content.

#![no_main]
#![cfg(feature = "libfuzzer")]

use libfuzzer_sys::fuzz_target;
use std::sync::atomic::{AtomicU32, Ordering};

use kit_fuzz::{MAX_ITER, bridge_map_one_iteration, run_one};

static ITERS: AtomicU32 = AtomicU32::new(0);

fuzz_target!(|data: &[u8]| {
    let n = ITERS.fetch_add(1, Ordering::Relaxed);
    if n >= MAX_ITER {
        return;
    }
    let _ = run_one(data, bridge_map_one_iteration);
});
